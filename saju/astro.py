def to_jd(dt: datetime) -> float:
    """timezone-aware datetime → Julian Day (UT)."""
    return JD_UNIX_EPOCH + dt.astimezone(timezone.utc).timestamp() / 86400.0


def from_jd(jd: float) -> datetime:
    return datetime.fromtimestamp((jd - JD_UNIX_EPOCH) * 86400.0, tz=timezone.utc)


def jdn(d) -> int:
    """달력 날짜(그레고리력) → Julian Day Number (정오 기준 정수)."""
    a = (14 - d.month) // 12
    y = d.year + 4800 - a
    m = d.month + 12 * a - 3
    return d.day + (153 * m + 2) // 5 + 365 * y + y // 4 - y // 100 + y // 400 - 32045


def delta_t(year: float) -> float:
    """ΔT = TT − UT (초). Espenak·Meeus 다항식 (NASA 일식 자료)."""
    if year < 1900:
        u = (year - 1820) / 100
        return -20 + 32 * u * u
    if year < 1920:
        t = year - 1900
        return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4
    if year < 1941:
        t = year - 1920
        return 21.20 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3
    if year < 1961:
        t = year - 1950
        return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547
    if year < 1986:
        t = year - 1975
        return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718
    if year < 2005:
        t = year - 2000
        return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5
    if year < 2050:
        t = year - 2000
        return 62.92 + 0.32217 * t + 0.005589 * t ** 2
    u = (year - 1820) / 100
    return -20 + 32 * u * u - 0.5628 * (2150 - year) if year < 2150 else -20 + 32 * u * u


def _series(terms, tau: float) -> float:
    return sum(sum(a * math.cos(b + c * tau) for a, b, c in row) * tau ** i for i, row in enumerate(terms)) / 1e8


def solar_longitude(jde: float) -> float:
    """겉보기 태양 황경(도, 0~360). jde는 역학시(TT) 기준 율리우스일."""
    tau = (jde - 2451545.0) / 365250.0
    T = tau * 10
    lon = math.degrees(_series(_L, tau)) + 180.0                 # 일심 지구 → 지심 태양
    lon -= 0.09033 / 3600                                        # FK5 보정
    omega = math.radians(125.04452 - 1934.136261 * T)
    ls, lm = math.radians(280.4665 + 36000.7698 * T), math.radians(218.3165 + 481267.8813 * T)
    nut = -17.20 * math.sin(omega) - 1.32 * math.sin(2 * ls) - 0.23 * math.sin(2 * lm) + 0.21 * math.sin(2 * omega)
    lon += nut / 3600 - 20.4898 / 3600 / _series(_R, tau)        # 장동 + 광행차
    return lon % 360.0


@lru_cache(maxsize=1024)
def term_time(year: int, target_deg: float) -> datetime:
    """해당 연도(UTC 기준) 안에서 태양 황경이 target_deg가 되는 시각.
    315°(입춘)~285°(소한)까지 12절 모두 이 함수로 구한다."""
    # 대략적인 시작점: 춘분(0°) ≈ 3월 20일, 하루 약 0.9856°
    approx = datetime(year, 3, 20, tzinfo=timezone.utc) + timedelta(days=((target_deg % 360) / 360.0) * 365.2422)
    if target_deg >= 285:                          # 소한·입춘·경칩은 연초 (전년도 춘분 기준)
        approx -= timedelta(days=365.2422)
    jde = to_jd(approx)
    for _ in range(10):
        diff = (target_deg - solar_longitude(jde) + 180.0) % 360.0 - 180.0
        jde += diff / 360.0 * 365.2422
        if abs(diff) < 1e-7:
            break
    return from_jd(jde - delta_t(year + (target_deg - 280) % 360 / 360) / 86400.0)    # TT → UT


